import puppeteer from 'puppeteer-core';
const chrome='/home/ayhem/.cache/hyperframes/chrome/chrome-headless-shell/linux-152.0.7977.30/chrome-headless-shell-linux64/chrome-headless-shell';
const b=await puppeteer.launch({executablePath:chrome,args:['--no-sandbox','--disable-gpu','--hide-scrollbars']});
const p=await b.newPage(); await p.setViewport({width:1440,height:1000});
const errs=[]; p.on('pageerror',e=>errs.push(e.message)); p.on('console',m=>{if(m.type()==='error')errs.push(m.text())});
await p.goto('https://arcadefork.pages.dev/',{waitUntil:'networkidle0',timeout:60000});
console.log('title:', await p.title());
console.log('theme:', await p.evaluate(()=>document.documentElement.dataset.theme));
console.log('tiles:', await p.evaluate(()=>document.querySelectorAll('.tile').length));
await p.screenshot({path:'/tmp/af-shots/live-home.png'});
await p.click('#btn-theme'); await new Promise(r=>setTimeout(r,250));
await p.click('[data-theme-id="coinop"]'); await new Promise(r=>setTimeout(r,350));
console.log('after coinop:', await p.evaluate(()=>document.documentElement.dataset.theme));
await p.screenshot({path:'/tmp/af-shots/live-coinop.png'});
// one game page, live
await p.goto('https://arcadefork.pages.dev/games/merge/',{waitUntil:'networkidle0',timeout:60000});
await p.click('[data-act="play"]'); await new Promise(r=>setTimeout(r,500));
await p.screenshot({path:'/tmp/af-shots/live-game.png'});
console.log('game canvas:', await p.evaluate(()=>{const c=document.getElementById('game');return c.width+'x'+c.height}));
console.log('errors:', errs.length?errs.slice(0,4):'none');
await b.close();
