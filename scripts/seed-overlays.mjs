/**
 * Seed `content/overlays.json` from the copy synthesiser.
 *
 *   node scripts/seed-overlays.mjs            # rewrite overlays for harvested games
 *   node scripts/seed-overlays.mjs --dry-run  # print counts only
 *
 * Why a script and not hand-written copy: the catalogue is going to ~600 games,
 * and every harvested page used to inherit its "How to play" from the repo
 * README - which told players to `npm install`, or handed them a raw URL. The
 * synthesiser in scripts/harvest/copy.mjs turns a repo into player-facing copy
 * deterministically; this writes the result where the site builder can read it
 * without ever touching content/games.generated.json (which harvest rewrites).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { copyFor, familyFor, cleanTitle } from './harvest/copy.mjs';
import { categoryFor } from './harvest/category.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dryRun = process.argv.includes('--dry-run');
const read = (p, fallback) => {
  const file = join(root, p);
  if (!existsSync(file)) return fallback;
  return JSON.parse(readFileSync(file, 'utf8'));
};

const generated = read('content/games.generated.json', { games: [] }).games ?? [];
const previous = read('content/overlays.json', { games: {} });

/** What the layers already publish before overlays run, so ids/dupes are real. */
const base = read('content/games.json', { games: [] }).games ?? [];
const engine = read('content/engine-new.json', { games: [] }).games ?? [];
const curated = read('content/curated.json', { games: [] }).games ?? [];
const published = read('content/harvest-published.json', { games: [] }).games ?? [];

const takenIds = new Set([...base, ...engine, ...curated, ...published].map((g) => g.id));
const overlays = { ...previous.games };

/** Titles seen so far, so two repos called "Snake Game" do not collide. */
const titles = new Map();
for (const g of [...base, ...engine, ...curated, ...published]) {
  titles.set(g.title.toLowerCase().replace(/[^a-z0-9 ]/g, '').replace(/\s+/g, ' ').trim(), g.id);
}

let rewritten = 0;
let recategorised = 0;

for (const game of generated) {
  if (takenIds.has(game.id)) continue; // a curated/engine layer already owns this id
  const repo = game.credit?.source?.replace(/^https?:\/\/github\.com\//, '') ?? '';
  const family = familyFor(`${game.title} ${game.description ?? ''}`);
  const copy = copyFor({ title: game.title, repo, description: game.description, family });
  const category = categoryFor(family, game.title, game.description);

  let title = cleanTitle(repo, game.description) || game.title;
  const key = title.toLowerCase().replace(/[^a-z0-9 ]/g, '').replace(/\s+/g, ' ').trim();
  if (titles.has(key) && titles.get(key) !== game.id) {
    // Disambiguate with the author, which is what a player would recognise.
    const owner = repo.split('/')[0]?.replace(/[^a-z0-9]+/gi, ' ').trim();
    if (owner) title = `${title} (${owner.replace(/\b\w/g, (c) => c.toUpperCase())})`;
  }
  titles.set(title.toLowerCase().replace(/[^a-z0-9 ]/g, '').replace(/\s+/g, ' ').trim(), game.id);

  const patch = {
    category,
    title,
    copy: {
      tagline: copy.tagline,
      description: copy.description,
      howToPlay: copy.howToPlay,
      faq: copy.faq,
      keywords: copy.keywords,
    },
  };
  if (category !== game.category) recategorised += 1;
  overlays[game.id] = patch;
  rewritten += 1;
}

const out = {
  _comment:
    'Per-game patches applied after every catalogue layer: category, title, copy. ' +
    'Generated by scripts/seed-overlays.mjs from scripts/harvest/copy.mjs - rerun it ' +
    'after a harvest instead of editing content/games.generated.json.',
  games: overlays,
};

const categories = {};
for (const patch of Object.values(overlays)) {
  categories[patch.category] = (categories[patch.category] ?? 0) + 1;
}

console.log(
  `seed-overlays: ${rewritten} games rewritten, ${recategorised} recategorised, ` +
    `${Object.keys(overlays).length} overlays total`,
);
console.log('categories:', JSON.stringify(categories));

if (!dryRun) {
  writeFileSync(join(root, 'content/overlays.json'), `${JSON.stringify(out, null, 2)}\n`);
  console.log('wrote content/overlays.json');
}
